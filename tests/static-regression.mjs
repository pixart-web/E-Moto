import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const app=read('app.js'),state=read('api/state.php'),backup=read('api/backup-lib.php'),admin=read('api/admin-users.php'),cheques=read('api/cheque-notifications.php');
const android=read('android-app/app/src/main/java/pt/motogreen/emoto/MainActivity.java');
assert.match(app,/const processOutstanding = process =>[^\r\n]*processTradeInValue\(process\)/,'retoma deve abater à dívida');
assert.ok(app.includes(": (Number(process?.price)||0);"),'processo legado não deve somar acessórios duas vezes');
const processTotalExpression=app.match(/const processTotal = process => ([^;]+);/)?.[1];
assert.ok(processTotalExpression,'fórmula do total do processo deve existir');
const calculateProcessTotal=Function('process',`return (${processTotalExpression})`);
assert.equal(calculateProcessTotal({basePrice:10000,accessories:500,price:10500}),10500,'processo moderno soma acessórios uma vez');
assert.equal(calculateProcessTotal({price:10500,accessories:500}),10500,'processo legado mantém o total já acordado');
assert.match(app,/process\.basePrice=enteredBase;priceInput\.value=total/,'edição deve manter basePrice e total coerentes');
assert.doesNotMatch(app,/openProcessEditorAgreedTotalBase/,'editor não deve sobrepor o preço base legado com o total');
assert.match(app,/openChequeArrivalModalAmountBase/,'receção de moto deve preservar o valor do cheque');
assert.match(app,/<option value="boss"[^>]*>Boss<\/option>/,'editor de utilizadores deve permitir o cargo Boss');
assert.match(app,/item\.processUid=process\.uid/,'ligação stock-processo deve usar UID estável');
assert.match(app,/knownProcesses=new Set\(processes\)/,'retoma deve identificar o processo realmente criado');
assert.match(app,/processes\.find\(item=>!knownProcesses\.has\(item\)\);if\(!process\)return/,'retoma não pode cair no primeiro processo após uma criação recusada');
assert.match(state,/\$resourceReadPanels/,'leitura deve considerar dependências entre módulos');
assert.match(state,/\$resourceWritePanels/,'escrita deve considerar operações interligadas');
assert.match(state,/sameProcessUid/,'backend deve reconciliar stock pelo UID estável do processo');
assert.match(cheques,/\$sameStock && \$isLinked/,'aviso de cheque deve validar que a moto pertence ao processo');
assert.match(cheques,/beginTransaction\(\)/,'stock e fila de email devem ser atualizados em transação');
assert.match(cheques,/emotogreen_pending_cheque_emails/,'endpoint e cron devem partilhar o bloqueio da fila');
assert.match(cheques,/\$alreadyQueued/,'repetição não deve duplicar o mesmo aviso pendente');
assert.match(state,/FOR UPDATE/,'escritas devem bloquear o snapshot');
assert.match(state,/state_deleted_/,'eliminações devem criar tombstones');
assert.match(state,/incomingVersion !== \$storedVersion/,'concorrência deve validar versão');
assert.match(backup,/hash\('sha256'/,'backup deve validar checksums');
assert.match(backup,/dirname\(__DIR__, 2\).*e-motogreen-backups/,'backup deve ficar fora da pasta pública');
assert.match(admin,/contabilidade/,'contabilidade deve ser uma permissão atribuível');
assert.match(app,/currentUser\?\.role!=='employee'\)return false/,'roles desconhecidos não podem obter acesso por omissão');
assert.doesNotMatch(read('private/config.example.php'),/Motogreen\.\d+|OuOnjUs/,'exemplo não pode conter passwords reais');
assert.match(android,/e-moto\.motogreen\.pt/,'Android deve continuar ligado ao domínio E-Moto');
assert.match(read('android-app/app/src/main/res/values-it/strings.xml'),/<resources>/,'recursos italianos devem existir');
console.log('Static regression checks: OK');
